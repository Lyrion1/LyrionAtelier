#!/usr/bin/env node
/**
 * Rewrite sitemap.xml from the catalogue.
 * Query-string collection and gift filters are omitted; each of those
 * pages canonicalises to its path. Codex articles stay inside the markers
 * that scripts/publish-codex.mjs owns.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { REPO_ROOT } from './lib/catalog.mjs';

const SITE = 'https://lyrionatelier.com';
const TODAY = '2026-11-04';
const MAP_START = '<!-- codex-articles:start (generated by scripts/publish-codex.mjs) -->';
const MAP_END = '<!-- codex-articles:end -->';

const STATIC = [
  ['/', 'daily', '1.0'],
  ['/shop', 'daily', '0.9'],
  ['/oracle', 'weekly', '0.9'],
  ['/compatibility', 'weekly', '0.8'],
  ['/curated-for-gifting', 'weekly', '0.7'],
  ['/codex', 'weekly', '0.7'],
  ['/about', 'monthly', '0.6'],
  ['/gift-concierge', 'monthly', '0.5'],
  ['/birthday-book', 'monthly', '0.5'],
  ['/contact', 'monthly', '0.5'],
  ['/shipping', 'monthly', '0.4'],
  ['/partners', 'monthly', '0.4'],
  ['/privacy-policy', 'yearly', '0.3'],
  ['/terms-of-service', 'yearly', '0.3'],
  ['/refund-policy', 'yearly', '0.3']
];

function urlEntry(loc, freq, priority) {
  return `  <url>
    <loc>${loc}</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${priority}</priority>
  </url>`;
}

function productLoc(product) {
  const link = product.link;
  if (typeof link === 'string' && link.startsWith('/')) {
    const clean = link.split('?')[0].replace(/\.html$/, '');
    if (clean.includes('?')) return null;
    return `${SITE}${clean}`;
  }
  return `${SITE}/product?slug=${encodeURIComponent(product.slug)}`;
}

const catalogue = JSON.parse(await readFile(path.join(REPO_ROOT, 'data/catalogue.json'), 'utf8'));
const seen = new Set();
const blocks = [];
for (const [loc, freq, priority] of STATIC) {
  seen.add(SITE + (loc === '/' ? '/' : loc));
  blocks.push(urlEntry(loc === '/' ? `${SITE}/` : `${SITE}${loc}`, freq, priority));
}
for (const product of catalogue.products) {
  if (product.hidden === true) continue;
  const loc = productLoc(product);
  if (!loc || seen.has(loc)) continue;
  if (loc.includes('?collection=') || loc.includes('?for=')) continue;
  seen.add(loc);
  const freq = loc.includes('/oracle/') || loc.includes('/compatibility/') ? 'monthly' : 'weekly';
  blocks.push(urlEntry(loc, freq, '0.7'));
}

const previous = await readFile(path.join(REPO_ROOT, 'sitemap.xml'), 'utf8');
const start = previous.indexOf(MAP_START);
const end = previous.indexOf(MAP_END);
const codex = start !== -1 && end !== -1
  ? previous.slice(start, end + MAP_END.length)
  : `${MAP_START}\n  ${MAP_END}`;

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${blocks.join('\n')}
${codex}
</urlset>
`;
await writeFile(path.join(REPO_ROOT, 'sitemap.xml'), xml);
console.log(`sitemap urls ${blocks.length}`);
